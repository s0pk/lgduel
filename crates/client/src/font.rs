/// Lit pixels of `c` as (col, row); unknown characters draw as a box.
pub fn glyph(c: char) -> Option<impl Iterator<Item = (usize, usize)>> {
    if c == ' ' {
        return None;
    }
    let c = c.to_ascii_uppercase();
    let rows = GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map(|(_, r)| *r)
        .unwrap_or([
            "#####", "#   #", "#   #", "#   #", "#   #", "#   #", "#####",
        ]);
    Some(rows.into_iter().enumerate().flat_map(|(y, row)| {
        row.bytes()
            .enumerate()
            .filter(|(_, b)| *b == b'#')
            .map(move |(x, _)| (x, y))
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_glyphs_well_formed_and_unique() {
        for (c, rows) in GLYPHS {
            assert!(rows.iter().all(|r| r.len() == GLYPH_W), "glyph {c}");
            assert!(rows.iter().any(|r| r.contains('#')), "glyph {c} empty");
        }
        let mut seen: Vec<char> = GLYPHS.iter().map(|(c, _)| *c).collect();
        seen.sort();
        seen.dedup();
        assert_eq!(seen.len(), GLYPHS.len());
        // Distinct shapes for the characters the HUD relies on.
        let bits = |c| glyph(c).unwrap().collect::<Vec<_>>();
        for (a, b) in [('0', 'O'), ('1', 'I'), ('5', 'S'), ('8', 'B')] {
            assert_ne!(bits(a), bits(b), "{a} vs {b}");
        }
    }

    #[test]
    fn lowercase_and_space() {
        assert!(glyph(' ').is_none());
        assert_eq!(glyph('a').unwrap().count(), glyph('A').unwrap().count());
        assert_eq!(glyph('~').unwrap().count(), 20); // fallback box
    }
}
